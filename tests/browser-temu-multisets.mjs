import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createWorkbench,root} from '../src/server.mjs';
import {clickRequired,getInteractionMetrics} from '../tools/interaction.mjs';

const directory=fs.mkdtempSync(path.join(os.tmpdir(),'ec-multiset-ui-'));
const output=path.join(root,'tests/results/temu-multisets');fs.mkdirSync(output,{recursive:true});
const captured=[],errors=[];
const image=fs.readFileSync(path.join(root,'public/mode-samples/fast_case2.jpg'));
let release;const gate=new Promise(resolve=>{release=resolve;});
const app=createWorkbench({dataDirectory:directory,configuration:{},provider:async payload=>{captured.push(payload);await gate;return image;}});
const imageUrl=app.saveImage(image);
await new Promise(resolve=>app.server.listen(0,'127.0.0.1',resolve));
const base='http://127.0.0.1:'+app.server.address().port;
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
await context.addInitScript(state=>{
  localStorage.setItem('aplus_newbie_tour_v1','true');
  const key='hyrule_state_v13::temu::'+location.host;
  if(!localStorage.getItem(key))localStorage.setItem(key,JSON.stringify(state));
},{generationMode:'master',designScope:'custom',customLayout:{main:1,sub:1,aplus:1,aplusType:'premium'},prodName:'裂变界面测试产品',prodDesc:'验证独立方案、恢复和下载的测试资料。',imageSlots:[{url:imageUrl,id:'old_single_result'},...Array(13).fill(null)],activeKieTasks:[],materialMeta:[{id:'reference',filename:'产品主体图.jpg',category:'产品主体图',url:imageUrl}],modelChoice:'gpt-image-2.5-sunburst'});
const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));page.on('dialog',dialog=>dialog.accept());
try{
  await page.goto(base);await page.waitForLoadState('networkidle');
  await page.waitForFunction(()=>document.getElementById('prodName').value==='裂变界面测试产品');
  await clickRequired(page.locator('#nav-dash'));
  assert.equal(await page.locator('#imageRatio').inputValue(),'1:1');assert.equal(await page.locator('#imageRatio').isDisabled(),true);
  await clickRequired(page.locator('#multiSetBtn'));
  assert.equal(await page.locator('#msCustomCount').getAttribute('max'),'20');
  await page.locator('#msCount').selectOption('2');
  assert.match(await page.locator('#msEstimate').innerText(),/每套 3 张 × 2 套 = 6 张/);
  assert.equal(await page.locator('#msCustomWrap').isVisible(),false);
  await clickRequired(page.locator('#msRecommend'));
  await page.waitForFunction(()=>document.querySelectorAll('.ms-direction').length===2);
  await page.locator('.ms-direction [data-field="audience"]').first().fill('喜欢简洁家居的用户');
  await clickRequired(page.locator('#msPlanAll'));
  await page.waitForSelector('#msGenerateAll');
  const id=await page.evaluate(()=>localStorage.getItem('temu_multisets_selected'));
  assert.equal((await fetch(base+'/api/temu/multisets/'+id).then(r=>r.json())).sets[0].direction.audience,'喜欢简洁家居的用户');
  await clickRequired(page.locator('.ms-set details summary').first());
  const text=await page.locator('[data-plan]').first().inputValue();
  await page.locator('[data-plan]').first().fill(text+'\n补充：保留真实商品颜色。');
  await clickRequired(page.locator('[data-action="save-plan"]').first());
  await clickRequired(page.locator('#msGenerateAll'));
  await page.waitForFunction(()=>document.querySelector('#msGroup').textContent.includes('图片生成中'));
  await page.reload();await page.waitForLoadState('networkidle');
  await page.waitForSelector('#view-multisets:not(.hidden) .ms-set');
  assert.equal(await page.locator('.ms-set').count(),2);
  // Consecutive read failures must reconnect without a new generation submission.
  let reads=0;
  await page.route('**/api/temu/multisets/'+id,route=>route.request().method()==='GET'&&++reads<=2?route.abort('failed'):route.continue());
  await page.waitForFunction(()=>document.querySelector('#msNotice').textContent.includes('进度读取失败'),{},{timeout:15000});
  release();
  await page.waitForFunction(()=>document.querySelector('#msGroup .ms-count')?.textContent==='已生成 6 / 6 张',{},{timeout:30000});
  assert.equal(captured.length,6);assert.ok(captured.every(p=>p.model==='gpt-image-2.5-sunburst'));
  await page.waitForFunction(()=>[...document.querySelectorAll('.ms-image img')].every(img=>img.complete&&img.naturalWidth>0));
  assert.ok(await page.locator('.ms-image img').evaluateAll(images=>images.every(img=>{
    const box=img.getBoundingClientRect();return Math.abs(box.height-box.width*img.naturalHeight/img.naturalWidth)<1;
  })),'preview preserves the actual image ratio without contain padding');
  await page.unroute('**/api/temu/multisets/'+id);
  await page.reload();await page.waitForLoadState('networkidle');
  await page.waitForFunction(()=>document.querySelectorAll('.ms-image img').length===6);
  assert.equal(captured.length,6,'reload does not create paid image requests');
  await page.screenshot({path:path.join(output,'desktop-results.png'),animations:'disabled'});
  const downloadEvent=page.waitForEvent('download');
  await clickRequired(page.locator('[data-action="download-all"]'));
  const download=await downloadEvent;await download.saveAs(path.join(output,'sets.zip'));
  const entries=await page.evaluate(async bytes=>{
    const archive=await JSZip.loadAsync(bytes,{base64:true});
    return Object.keys(archive.files);
  },fs.readFileSync(path.join(output,'sets.zip')).toString('base64'));
  assert.equal(entries.filter(name=>/\.(jpg|png|webp)$/.test(name)).length,6);
  assert.equal(entries.filter(name=>name.endsWith('设计方案.txt')).length,2);
  assert.ok(entries.includes('listing-manifest.json'));
  assert.ok(captured.every(p=>p.ratio==='1:1'&&p.platform==='temu'));
  const manifest=await page.evaluate(async bytes=>JSON.parse(await (await JSZip.loadAsync(bytes,{base64:true})).file('listing-manifest.json').async('text')),fs.readFileSync(path.join(output,'sets.zip')).toString('base64'));
  assert.equal(manifest.setCount,2);for(const set of manifest.sets)assert.deepEqual(set.mainImages,set.detailImages);
  await clickRequired(page.locator('[data-action="regenerate"]').first());
  await page.waitForFunction(async key=>{const g=await fetch('/api/temu/multisets/'+key).then(r=>r.json());return g.phase==='completed'&&g.sets[0].images[0].attempts.length===2;},id);
  assert.equal(captured.length,7,'single-image retry submits exactly one image');
  await page.waitForSelector('.ms-link');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(output,'mobile-results.png'),animations:'disabled'});
  assert.equal(await page.locator('#view-multisets').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,'feature panel fits mobile width');
  await page.setViewportSize({width:1440,height:1000});
  await clickRequired(page.locator('[data-action="copy"]'));
  await page.locator('#msCount').selectOption('5');
  assert.match(await page.locator('#msEstimate').innerText(),/每套 3 张 × 5 套 = 15 张/);
  assert.match(await page.locator('#msSettings').innerText(),/原批次.*gpt-image-2.5-sunburst/);
  await clickRequired(page.locator('[data-action="source"]'));
  assert.equal(await page.locator('#view-dashboard').isVisible(),true);
  assert.ok(!page.url().includes('#multisets'));
  await clickRequired(page.locator('#multiSetBtn'));
  assert.match(await page.locator('#msSettings').innerText(),/工作台设置/);
  assert.deepEqual(errors,[]);
  const interactions=getInteractionMetrics(context);assert.ok(interactions.minimumGapMs>=2500);
  fs.writeFileSync(path.join(output,'browser-report.json'),JSON.stringify({passed:true,scope:'isolated UI fixture, no external image calls; sample imagery is not generated output',imageCalls:captured.length,zipEntries:entries,errors,interactions},null,2));
  console.log('Temu shared UI passed: independent sets, editable plans, refresh/network recovery, grouped ZIP, single image retry, prior result, copied snapshot, mobile layout and dashboard return.');
}finally{release();await browser.close();await new Promise(resolve=>app.server.close(resolve));fs.rmSync(directory,{recursive:true,force:true});}
